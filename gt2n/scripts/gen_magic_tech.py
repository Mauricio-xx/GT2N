"""Generate the Magic VLSI technology files of the GT2N PDK.

Writes libs.tech/magic/{gt2n.tech, gt2n.magicrc, gt2n.tcl}.

Scope: this is a *layout-level* technology. All GT2N front-end and
frontside GDS layers are represented (so cell and frontside-PDN layouts
round-trip through Magic), the metal/via stack is connected for net tracing
and abstract extraction, and the routing layers carry the minimum
width/spacing rules of the tech LEF. The backside stack (BM1-BM4, BRDL,
BV0-BV4 on GDS layers 910-1000) is omitted because Magic only supports GDS
layer numbers up to 255; use KLayout for backside-PDN layouts. Nanosheet device extraction is NOT modelled; transistor-level
LVS of GT2N layouts is done with the KLayout deck (libs.tech/klayout).

Internal unit: 1 Magic unit = 0.5 nm (the GT2N manufacturing grid).

Usage: gen_magic_tech.py [--check]
"""

import argparse
import sys

from gt2n_common import LIBS_TECH

# (magic type, GDS layer, plane, display style, long name)
FEOL = [
    ("nwell", 1, "nwell", "nwell", "NWELL"),
    ("act", 2, "active", "ndiffusion", "ACT"),
    ("gate", 3, "gate", "polysilicon", "GATE"),
    ("dummy", 4, "dummy", "obspoly", "DUMMY"),
    ("gcut", 5, "gcut", "poly_resist", "GCUT"),
    ("nsel", 6, "nsel", "nselect", "NSEL"),
    ("psel", 7, "psel", "pselect", "PSEL"),
    ("sdcon", 10, "sdcon", "metal1_alt", "SDCON"),
    ("elvt", 94, "vtelvt", "implant1", "ELVT"),
    ("ulvt", 95, "vtulvt", "implant2", "ULVT"),
    ("svt", 96, "vtsvt", "implant3", "SVT"),
    ("hvt", 97, "vthvt", "implant4", "HVT"),
    ("sramvt", 98, "vtsram", "implant1", "SRAMVT"),
]

# Routing layers: (magic type, GDS layer, plane, display style, LEF name,
#                  min width nm, min spacing nm)
METALS = [
    ("bpr", 8, "bpr", "metal9", "BPR", 32, 112),
    ("m0", 20, "metal0", "metal1", "M0", 12, 12),
    ("m1", 25, "metal1", "metal2", "M1", 14, 14),
    ("m2", 30, "metal2", "metal3", "M2", 12, 12),
    ("m3", 35, "metal3", "metal4", "M3", 14, 14),
    ("m4", 40, "metal4", "metal5", "M4", 21, 21),
    ("m5", 45, "metal5", "metal6", "M5", 21, 21),
    ("m6", 50, "metal6", "metal7", "M6", 38, 38),
    ("m7", 55, "metal7", "metal8", "M7", 38, 38),
    ("m8", 60, "metal8", "metal9", "M8", 38, 38),
    ("m9", 65, "metal9", "metal1", "M9", 38, 38),
    ("m10", 70, "metal10", "metal2", "M10", 56, 56),
    ("m11", 75, "metal11", "metal3", "M11", 56, 56),
    ("m12", 80, "metal12", "metal4", "M12", 360, 360),
    ("m13", 85, "metal13", "metal5", "M13", 360, 360),
    ("rdl", 90, "rdl", "metal6", "RDL", 1600, 1600),
    # The backside stack BM1-BM4/BRDL (GDS 920-1000) and its vias BV0-BV4
    # cannot be represented: Magic limits GDS layer numbers to 0..255.
]

# Cuts: (magic type, GDS layer, lower type, upper type, LEF name, width nm)
VIAS = [
    ("vbpr", 9, "bpr", "sdcon", "VBPR", 11),
    ("vsd", 11, "sdcon", "m0", "VSD", 12),
    ("vg", 12, "gate", "m0", "VG", 12),
    ("v0", 22, "m0", "m1", "V0", 12),
    ("v1", 27, "m1", "m2", "V1", 12),
    ("v2", 32, "m2", "m3", "V2", 12),
    ("v3", 37, "m3", "m4", "V3", 14),
    ("v4", 42, "m4", "m5", "V4", 21),
    ("v5", 47, "m5", "m6", "V5", 21),
    ("v6", 52, "m6", "m7", "V6", 38),
    ("v7", 57, "m7", "m8", "V7", 38),
    ("v8", 62, "m8", "m9", "V8", 38),
    ("v9", 67, "m9", "m10", "V9", 38),
    ("v10", 72, "m10", "m11", "V10", 56),
    ("v11", 77, "m11", "m12", "V11", 56),
    ("v12", 82, "m12", "m13", "V12", 56),
    ("v13", 87, "m13", "rdl", "V13", 56),
]

PIN_DT = 251
LABEL_DT = 20
BOUNDARY = (235, 250)


def u(nm):
    """nm -> Magic internal units (0.5 nm)."""
    return int(round(nm * 2))


def tech_text():
    out = []
    w = out.append
    w("# SPDX-License-Identifier: BSD-3-Clause")
    w("#")
    w("# Magic technology file for the GT2N 2 nm nanosheet PDK (layout level).")
    w("# THIS FILE IS GENERATED by gt2n/scripts/gen_magic_tech.py -- do not edit.")
    w("# 1 internal unit = 0.5 nm. No nanosheet device extraction (see the")
    w("# KLayout LVS deck for transistor-level LVS).")
    w("")
    w("tech\n  format 35\n  gt2n\nend\n")
    w("version\n  version 0.1\n  description \"GT2N 2nm GAAFET/BSPDN, layout-level Magic tech\"\nend\n")

    planes = [p for _, _, p, _, _ in FEOL] + [m[2] for m in METALS] + ["comment"]
    w("planes")
    for p in planes:
        w(f"  {p}")
    w("end\n")

    w("types")
    for t, _, p, _, _ in FEOL:
        w(f"  {p} {t}")
    for t, _, p, *_ in METALS:
        w(f"  {p} {t}")
    plane_of = {t: p for t, _, p, _, _ in FEOL}
    plane_of.update({m[0]: m[2] for m in METALS})
    for v, _, lo, hi, _, _ in VIAS:
        w(f"  {plane_of[lo]} {v}")
    w("  comment boundary")
    w("end\n")

    w("contact")
    for v, _, lo, hi, _, _ in VIAS:
        w(f"  {v} {lo} {hi}")
    # GT2N stacks vias (e.g. VG under V0 on the same M0 landing).
    w("  stackable")
    w("end\n")

    w("aliases")
    w("  allm1 m1,v0,v1")
    w("end\n")

    w("styles\n  styletype mos")
    for t, _, _, style, _ in FEOL:
        w(f"  {t} {style}")
    for t, _, _, style, *_ in METALS:
        w(f"  {t} {style}")
    for v, *_ in VIAS:
        w(f"  {v} via1")
    w("  boundary subcircuit")
    w("end\n")

    w("compose\nend\n")

    w("connect")
    for v, _, lo, hi, _, _ in VIAS:
        w(f"  {v} {lo},{hi}")
    w("end\n")

    w("cifoutput")
    w("style gds\n  scalefactor 5 angstroms\n  units angstroms\n  options calma-permissive-labels")
    for t, layer, _, _, name in FEOL:
        types = [t] + [v for v, _, lo, hi, _, _ in VIAS if t in (lo, hi)]
        w(f"  layer {name} {','.join(types)}\n    labels {t}\n    calma {layer} 0")
    for t, layer, _, _, name, *_ in METALS:
        types = [t] + [v for v, _, lo, hi, _, _ in VIAS if t in (lo, hi)]
        w(f"  layer {name} {','.join(types)}\n    labels {t}\n    calma {layer} 0")
        w(f"  layer {name}P\n    labels {t} port\n    calma {layer} {PIN_DT}")
    for v, layer, _, _, name, _ in VIAS:
        w(f"  layer {name} {v}\n    calma {layer} 0")
    w(f"  layer BOUNDARY boundary\n    calma {BOUNDARY[0]} {BOUNDARY[1]}")
    w("end\n")

    w("cifinput")
    w("style gds\n  scalefactor 5 angstroms")
    for t, layer, _, _, name in FEOL:
        w(f"  layer {t} {name}\n    labels {name}\n    calma {name} {layer} 0")
    for t, layer, _, _, name, *_ in METALS:
        w(f"  layer {t} {name}\n    labels {name}\n    calma {name} {layer} 0")
        w(f"  layer {t} {name}P\n    labels {name}P port\n    calma {name}P {layer} {PIN_DT}")
        w(f"  layer {t} {name}L\n    labels {name}L\n    calma {name}L {layer} {LABEL_DT}")
    for v, layer, _, _, name, _ in VIAS:
        w(f"  layer {v} {name}\n    calma {name} {layer} 0")
    w(f"  layer boundary BND\n    calma BND {BOUNDARY[0]} {BOUNDARY[1]}")
    w("end\n")


    w("drc")
    w("  # Minimum width / spacing of the routing stack (tech LEF values).")
    for t, _, _, _, name, width, space in METALS:
        types = ",".join([t] + [v for v, _, lo, hi, _, _ in VIAS if t in (lo, hi)])
        w(f"  width {types} {u(width)} \"{name} width < {width} nm\"")
        w(f"  spacing {types} {types} {u(space)} touching_ok \"{name} spacing < {space} nm\"")
    w("end\n")

    w("extract")
    w("  style default\n  cscale 1\n  lambda 0.05\n  step 100\n  sidehalo 8")
    order = ", ".join(planes)
    w(f"  planeorder {planes[0]} 0")
    for i, p in enumerate(planes[1:], start=1):
        w(f"  planeorder {p} {i}")
    w("end\n")

    # Magic needs the drc section to be read before the lef section.
    w("lef")
    for t, *_rest in METALS:
        w(f"  routing {t} {_rest[3]}")
    for v, _, _, _, name, _ in VIAS:
        w(f"  cut {v} {name}")
    w("  masterslice gate GATE")
    w("  masterslice act ACT")
    w("  masterslice nwell NW NWELL")
    w("end\n")
    w("wiring\nend\n")
    w("router\nend\n")
    w("plowing\nend\n")
    w("plot\nend\n")
    return "\n".join(out)


MAGICRC = """\
# SPDX-License-Identifier: BSD-3-Clause
# Magic startup file for the GT2N PDK. Set PDK_ROOT (and PDK=gt2n) first.
# THIS FILE IS GENERATED by gt2n/scripts/gen_magic_tech.py.
if {![info exists PDK_ROOT]} {
    if {[info exists env(PDK_ROOT)]} { set PDK_ROOT $env(PDK_ROOT) }
}
if {![info exists PDK]} {
    if {[info exists env(PDK)]} { set PDK $env(PDK) } else { set PDK gt2n }
}
set PDKPATH $PDK_ROOT/$PDK
tech load $PDKPATH/libs.tech/magic/gt2n.tech
source $PDKPATH/libs.tech/magic/gt2n.tcl
"""

SETUP_TCL = """\
# SPDX-License-Identifier: BSD-3-Clause
# GT2N PDK setup for Magic (sourced by gt2n.magicrc / LibreLane
# MAGIC_PDK_SETUP). THIS FILE IS GENERATED by gt2n/scripts/gen_magic_tech.py.
#
# The GT2N standard cells ship as GDS and LEF only; read them with e.g.
#   gds read $PDKPATH/libs.ref/gt2_6t_w31_lvt/gds/gt2_6t_w31_lvt.gds
#   lef read $PDKPATH/libs.ref/gt2_6t_w31_lvt/lef/gt2_6t_w31_lvt.lef
units internal
gds ordering on
gds flatglob *_CDNS_*
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    outdir = LIBS_TECH / "magic"
    files = {"gt2n.tech": tech_text(), "gt2n.magicrc": MAGICRC, "gt2n.tcl": SETUP_TCL}
    stale = False
    for name, text in files.items():
        dst = outdir / name
        if dst.is_file() and dst.read_text() == text:
            continue
        stale = True
        if args.check:
            print(f"out of date: {dst}")
        else:
            outdir.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
            print(f"wrote {dst.relative_to(LIBS_TECH.parent)}")
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
