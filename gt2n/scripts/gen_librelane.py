PHYSICAL_ONLY = ("filler", "tapfspdn", "tapbspdn", "decapcc")
# Kept out of synthesis: the upstream mux2_x1 layout violates the legacy rule
# V0.M1.1 (rV0_9), see libs.qa/stdcells/drc_waivers.txt. LibreLane checks
# blocks in KLayout route mode, which does not cover that rule.
SYNTH_ONLY_EXCLUDED = ("mux2_x1",)


def files():
    out = {}
    out["config.tcl"] = PDK_CONFIG.format(
        header=HEADER,
        layers_rc="\n".join(f'dict set ::env(LAYERS_RC) "*" {l} res {r:.6e}\n'
                            f'dict set ::env(LAYERS_RC) "*" {l} cap {c:.6e}'
                            for l, r, c in LAYERS_RC),
        vias_r="\n".join(f'dict set ::env(VIAS_R) "*" {v} res {r}' for v, r in VIAS_R),
    )
    out["tracks.info"] = "".join(f"{l} X {o:.3f} {p:.3f}\n{l} Y {o:.3f} {p:.3f}\n"
                                 for l, o, p in TRACKS)
    for lib in all_libs():
        flavor = lib[len("gt2_6t_"):]
        out[f"{lib}/config.tcl"] = SCL_CONFIG.format(header=HEADER, lib=lib, flavor=flavor)
        excluded = "".join(f"gt2_6t_{c}_{flavor}\n" for c in PHYSICAL_ONLY)
        out[f"{lib}/synth_exclude.cells"] = excluded + "".join(
            f"gt2_6t_{c}_{flavor}\n" for c in SYNTH_ONLY_EXCLUDED)
        out[f"{lib}/pnr_exclude.cells"] = excluded
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    root = LIBS_TECH / "librelane"
    stale = False
    for rel, text in files().items():
        dst = root / rel
        if dst.is_file() and dst.read_text() == text:
            continue
        stale = True
        if args.check:
            print(f"out of date: {dst}")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
            print(f"wrote {dst.relative_to(LIBS_TECH.parent)}")
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
