"""Generate the LibreLane configuration of the GT2N PDK.

Writes, under libs.tech/librelane/:
    config.tcl               PDK-level configuration (all flavours)
    tracks.info              routing tracks of the frontside router view
    <lib>/config.tcl         standard-cell-library configuration
    <lib>/synth_exclude.cells, <lib>/pnr_exclude.cells

The PDN script (gt2n_pdn_cfg.tcl) and the base SDC (gt2n_base.sdc) are
maintained by hand next to these files.

Usage: gen_librelane.py [--check]
"""

