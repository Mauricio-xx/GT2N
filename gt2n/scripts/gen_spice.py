"""Generate SPICE netlists of the GT2N standard cells for ngspice / Xyce.

The 4-terminal CDL (libs.ref/<lib>/cdl/<lib>.cdl) uses primitive MOSFET
instances (`M... nmos_lvt W= L= M=`). The open-source simulators instantiate
the GT2N nanosheet devices through the subcircuit wrappers defined in
libs.tech/ngspice/models/gt2n_<corner>.lib, so every M device becomes an X
instance with lower-case parameters. Hierarchical X instances and .subckt
headers are kept verbatim.

Usage: gen_spice.py [--check] [lib ...]
"""

import argparse
import re
import sys

from gt2n_common import LIBS_REF, all_libs

HEADER = """\
* SPDX-License-Identifier: BSD-3-Clause
*
* GT2N standard-cell library {lib}: SPICE netlist for ngspice / Xyce.
*
* Copyright 2025 Georgia Institute of Technology. See LICENSE in the GT2N
* repository root for the full BSD 3-Clause license text.
*
* THIS FILE IS GENERATED by gt2n/scripts/gen_spice.py from
* libs.ref/{lib}/cdl/{lib}.cdl -- do not edit by hand.
*
* Device wrappers (nmos_<vt> / pmos_<vt>, terminals d g s b) are defined in
* libs.tech/ngspice/models/gt2n_tt.lib, section w13 or w31.
"""


def convert_line(line):
    tok = line.split()
    if not tok or not tok[0][0] in "Mm":
        return line.rstrip("\n")
    # M<name> d g s b model param=value ...
    name, nodes, model, params = tok[0], tok[1:5], tok[5], tok[6:]
    out_params = []
    for p in params:
        key, _, val = p.partition("=")
        out_params.append(f"{key.lower()}={val}")
    return " ".join([f"X{name}", *nodes, model, *out_params])


def generate(lib):
    src = LIBS_REF / lib / "cdl" / f"{lib}.cdl"
    body = []
    in_header = True
    for line in src.read_text(encoding="utf-8", errors="replace").splitlines():
        # Skip the license banner of the CDL; the generated header carries it.
        if in_header and (line.startswith("*") or not line.strip()):
            continue
        in_header = False
        body.append(convert_line(line))
    text = HEADER.format(lib=lib) + "\n" + "\n".join(body).rstrip() + "\n"
    if re.search(r"^M", text, re.M):
        raise RuntimeError(f"{lib}: unconverted M device left")
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    parser.add_argument("libs", nargs="*", default=all_libs())
    args = parser.parse_args()
    stale = False
    for lib in args.libs:
        dst = LIBS_REF / lib / "spice" / f"{lib}.spice"
        text = generate(lib)
        if dst.is_file() and dst.read_text() == text:
            continue
        stale = True
        if args.check:
            print(f"out of date: {dst}")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
            print(f"wrote {dst.relative_to(LIBS_REF.parent)}")
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
