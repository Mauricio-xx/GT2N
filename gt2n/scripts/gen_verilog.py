"""Generate Verilog simulation models for the GT2N standard-cell libraries.

The models are derived from the typical-corner Liberty file (cell functions,
sequential groups and timing arcs) and the CDL netlist (port order):

  * combinational cells -> continuous assignments
  * flip-flops          -> a sequential UDP (accurate set/reset release
                           behaviour) or, for tools without UDP support
                           (Yosys, Verilator), an equivalent always block
  * physical-only cells -> empty modules (power ports only)

Power ports are only present when USE_POWER_PINS is defined, following the
convention used by LibreLane and the other open PDKs. Specify blocks with
zero delays describe the timing arcs so that SDF back-annotation works.

Usage: gen_verilog.py [--check] [lib ...]
"""

import argparse
import sys

import liberty
from gt2n_common import GROUND_PIN, LIBS_REF, POWER_PIN, all_libs

HEADER = """\
// SPDX-License-Identifier: BSD-3-Clause
//
// GT2N standard-cell library {lib}: Verilog simulation models.
//
// Copyright 2025 Georgia Institute of Technology. See LICENSE in the GT2N
// repository root for the full BSD 3-Clause license text.
//
// THIS FILE IS GENERATED by gt2n/scripts/gen_verilog.py from
// libs.ref/{lib}/lib/{liberty} -- do not edit by hand.

`timescale 1ns/1ps

// Tools without user-defined-primitive support get behavioural flip-flops.
`ifndef GT2N_NO_UDP
  `ifdef YOSYS
    `define GT2N_NO_UDP
  `endif
  `ifdef VERILATOR
    `define GT2N_NO_UDP
  `endif
`endif

`ifndef GT2N_NO_UDP
`ifndef GT2N_UDP_DFF_SR
`define GT2N_UDP_DFF_SR
// Rising-edge D flip-flop with active-low asynchronous reset and set.
// Set dominates when both are asserted (Liberty clear_preset_var1 : H).
primitive gt2n_udp_dff_sr (Q, D, CLK, RN, SN);
  output Q;
  reg Q;
  input D, CLK, RN, SN;
  table
  //  D   CLK   RN  SN  :  Q  :  Q+
      ?    ?     ?   0  :  ?  :  1 ;  // asynchronous set
      ?    ?     0   1  :  ?  :  0 ;  // asynchronous reset
      0   (01)   1   1  :  ?  :  0 ;
      1   (01)   1   1  :  ?  :  1 ;
      0   (01)   1   x  :  ?  :  0 ;
      1   (01)   x   1  :  ?  :  1 ;
      0   (x1)   1   1  :  0  :  0 ;
      1   (x1)   1   1  :  1  :  1 ;
      0   (0x)   1   1  :  0  :  0 ;
      1   (0x)   1   1  :  1  :  1 ;
      ?   (?0)   ?   ?  :  ?  :  - ;  // falling / steady clock: hold
      *    ?     ?   ?  :  ?  :  - ;  // data change without clock edge
      ?    ?    (?1) 1  :  ?  :  - ;  // release of reset
      ?    ?     1 (?1) :  ?  :  - ;  // release of set
      ?    0    (?1) ?  :  ?  :  - ;
      ?    0     ? (?1) :  ?  :  - ;
      ?    1    (?1) ?  :  ?  :  - ;
      ?    1     ? (?1) :  ?  :  - ;
      ?    ?     x   1  :  0  :  0 ;  // pessimism reduction
      ?    ?     1   x  :  1  :  1 ;
  endtable
endprimitive
`endif
`endif
"""


def cdl_port_order(cdl_path):
    order = {}
    with open(cdl_path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            tok = line.split()
            if tok and tok[0].lower() == ".subckt":
                order[tok[1]] = tok[2:]
    return order


def emit_cell(cell, ports):
    name = cell.name
    pins = {p.name: p for p in cell.children("pin")}
    signals = [p for p in ports if p in pins]
    signals += sorted(set(pins) - set(signals))
    pg = [p for p in (POWER_PIN, GROUND_PIN)]
    out = ["`celldefine", f"module {name} ("]
    if signals:
        out.append("    " + ",\n    ".join(signals))
        out += ["`ifdef USE_POWER_PINS", f"    , {pg[0]}, {pg[1]}", "`endif"]
    else:
        out += ["`ifdef USE_POWER_PINS", f"    {pg[0]}, {pg[1]}", "`endif"]
    out.append(");")

    for sig in signals:
        direction = pins[sig].get("direction", "input")
        kw = {"input": "input", "output": "output", "inout": "inout"}.get(direction, "input")
        out.append(f"  {kw} {sig};")
    out += ["`ifdef USE_POWER_PINS", f"  inout {pg[0]};", f"  inout {pg[1]};", "`endif"]

    ffs = cell.children("ff")
    latches = cell.children("latch")
    if latches:
        raise NotImplementedError(f"{name}: latch cells are not supported yet")
    body = []
    if ffs:
        ff = ffs[0]
        iq, iqn = (ff.args + [None])[:2]
        clk = ff.get("clocked_on").strip("() ")
        d = liberty.liberty_to_verilog(ff.get("next_state"))
        clear = ff.get("clear")
        preset = ff.get("preset")
        if not clk.isidentifier():
            raise NotImplementedError(f"{name}: complex clock {clk!r}")
        rn = sn = None
        if clear:
            rn = clear.replace("(", "").replace(")", "").replace("!", "").strip()
        if preset:
            sn = preset.replace("(", "").replace(")", "").replace("!", "").strip()
        if (clear and not clear.replace(" ", "").startswith(("(!", "!"))) or \
                (preset and not preset.replace(" ", "").startswith(("(!", "!"))):
            raise NotImplementedError(f"{name}: only active-low clear/preset supported")
        if ff.get("clear_preset_var1", "H") != "H" and clear and preset:
            raise NotImplementedError(f"{name}: clear_preset_var1 other than H")
        rn_expr = rn or "1'b1"
        sn_expr = sn or "1'b1"
        body += [
            f"  wire {iq};",
            "`ifdef GT2N_NO_UDP",
            f"  reg {iq}_r;",
            f"  always @(posedge {clk} or negedge {rn_expr} or negedge {sn_expr}) begin"
            if rn and sn else
            f"  always @(posedge {clk}" + (f" or negedge {rn}" if rn else "") +
            (f" or negedge {sn}" if sn else "") + ") begin",
        ]
        # Keep each `if (...)` on its own line: LibreLane's model pre-processor
        # drops lines shaped like `name (...) ...;` (cell instantiations).
        if sn:
            body += [f"    if (!{sn})", f"      {iq}_r <= 1'b1;"]
            if rn:
                body += [f"    else if (!{rn})", f"      {iq}_r <= 1'b0;"]
        elif rn:
            body += [f"    if (!{rn})", f"      {iq}_r <= 1'b0;"]
        if rn or sn:
            body += ["    else", f"      {iq}_r <= {d};"]
        else:
            body.append(f"    {iq}_r <= {d};")
        body += [
            "  end",
            f"  assign {iq} = {iq}_r;",
            "`else",
            f"  gt2n_udp_dff_sr u_ff ({iq}, {d}, {clk}, {rn_expr}, {sn_expr});",
            "`endif",
        ]
        if iqn:
            body.append(f"  wire {iqn} = ~{iq};")
        body = [b for b in body if b]

    for sig in signals:
        func = pins[sig].get("function")
        if pins[sig].get("direction") == "output" and func:
            body.append(f"  assign {sig} = {liberty.liberty_to_verilog(func)};")
    out += body

    # Zero-delay specify block mirroring the Liberty timing arcs.
    paths = []
    for sig in signals:
        for timing in pins[sig].children("timing"):
            related = timing.get("related_pin", "").split()
            ttype = timing.get("timing_type", "combinational")
            for rel in related:
                if ttype in ("combinational", "combinational_rise", "combinational_fall"):
                    paths.append(f"    ({rel} => {sig}) = (0, 0);")
                elif ttype == "rising_edge":
                    data = ffs[0].get("next_state").strip("() ") if ffs else rel
                    paths.append(f"    (posedge {rel} => ({sig} +: {data})) = (0, 0);")
                elif ttype == "falling_edge":
                    data = ffs[0].get("next_state").strip("() ") if ffs else rel
                    paths.append(f"    (negedge {rel} => ({sig} +: {data})) = (0, 0);")
                elif ttype in ("clear", "preset"):
                    paths.append(f"    ({rel} => {sig}) = (0, 0);")
    if paths:
        out += ["  specify"] + list(dict.fromkeys(paths)) + ["  endspecify"]
    out += ["endmodule", "`endcelldefine", ""]
    return "\n".join(out)


def generate(lib):
    libdir = LIBS_REF / lib
    libfiles = sorted((libdir / "lib").glob(f"{lib}_tt_*.lib")) or sorted((libdir / "lib").glob("*.lib"))
    lib_tree = liberty.read(libfiles[0])
    ports = cdl_port_order(libdir / "cdl" / f"{lib}.cdl")
    parts = [HEADER.format(lib=lib, liberty=libfiles[0].name)]
    for cell in sorted(lib_tree.children("cell"), key=lambda c: c.name):
        parts.append(emit_cell(cell, [p for p in ports.get(cell.name, [])
                                      if p not in (POWER_PIN, GROUND_PIN)]))
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    parser.add_argument("libs", nargs="*", default=all_libs())
    args = parser.parse_args()
    stale = False
    for lib in args.libs:
        dst = LIBS_REF / lib / "verilog" / f"{lib}.v"
        text = generate(lib)
        if dst.is_file() and dst.read_text() == text:
            continue
        stale = True
        if args.check:
            print(f"out of date: {dst}")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
            print(f"wrote {dst.relative_to(LIBS_REF.parent)}")
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
