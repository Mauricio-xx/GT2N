"""Generate libs.ref/<lib>/doc/<lib>.celllist (cell, area, function summary).

Usage: gen_doc.py [--check] [lib ...]
"""

import argparse
import sys

import liberty
from gt2n_common import LIBS_REF, all_libs


def describe(cell):
    if cell.children("ff"):
        ff = cell.children("ff")[0]
        parts = [f"rising-edge DFF D={ff.get('next_state')}"]
        if ff.get("clear"):
            parts.append(f"clear={ff.get('clear')}")
        if ff.get("preset"):
            parts.append(f"preset={ff.get('preset')}")
        return ", ".join(parts)
    funcs = [f"{p.name}={p.get('function')}" for p in cell.children("pin")
             if p.get("direction") == "output" and p.get("function")]
    if funcs:
        return "; ".join(funcs)
    return "physical-only (no logic function)"


def generate(lib):
    libdir = LIBS_REF / lib
    libfile = sorted((libdir / "lib").glob("*.lib"))[0]
    tree = liberty.read(libfile)
    rows = [(c.name, c.get("area", "-"), describe(c)) for c in tree.children("cell")]
    rows.sort()
    width = max(len(r[0]) for r in rows)
    lines = [
        f"# Cell list of GT2N standard-cell library {lib}",
        f"# Generated by gt2n/scripts/gen_doc.py from {libfile.name}.",
        f"# {len(rows)} cells; area in um^2.",
        "#",
        f"# {'cell'.ljust(width)}  {'area':>9}  function",
    ]
    for name, area, desc in rows:
        lines.append(f"{name.ljust(width + 2)}  {area:>9}  {desc}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    parser.add_argument("libs", nargs="*", default=all_libs())
    args = parser.parse_args()
    stale = False
    for lib in args.libs:
        dst = LIBS_REF / lib / "doc" / f"{lib}.celllist"
        text = generate(lib)
        if dst.is_file() and dst.read_text() == text:
            continue
        stale = True
        if args.check:
            print(f"out of date: {dst}")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text)
            print(f"wrote {dst.relative_to(LIBS_REF.parent)}")
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
